/** Найти гайд по названию упражнения */
export function findGuide(exerciseName: string): ExerciseGuide | null {
  const name = exerciseName.toLowerCase()
  for (const guide of EXERCISE_GUIDES) {
    if (guide.keywords.some((k) => name.includes(k))) return guide
  }
  return null
}
