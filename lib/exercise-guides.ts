export function findGuide(name: string): ExerciseGuide | undefined {
  const normalized = name.toLocaleLowerCase("ru-RU");
  return EXERCISE_GUIDES.find((guide) =>
    guide.keywords.some((keyword) => normalized.includes(keyword)),
  );
}
