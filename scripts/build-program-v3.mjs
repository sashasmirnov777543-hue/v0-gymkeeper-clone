const pickLadder = (works) => {
  if (works.some((w) => w[0] === "calib" || w[0] === "test")) return "ТЕСТ";
  const tops = works.filter((w) => w[3] != null).map((w) => w[3]);
  if (!tops.length) return "L0";
  const m = Math.max(...tops);
  return m <= 65 ? "L0" : m <= 72.5 ? "L1" : m <= 85 ? "L2" : "L3";
};
