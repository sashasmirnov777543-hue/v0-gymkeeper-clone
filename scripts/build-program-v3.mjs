function buildWork(spec, cycleAbs, wid) {
  const [kind, sets, reps, pct] = spec;
  const m = MAIN[kind];
  // Пиковый сингл Ц21 привязан к ветке теста, а не только к уровню допуска:
  // при тесте-тройке (ветка B, по умолчанию) он не выполняется вовсе.
  const peakSingle = kind === "single" && cycleAbs === 21;
  const base = {
    key: m.key, name: m.name, role: m.role,
    optional: kind === "single",
    condition: peakSingle
      ? "test_branch_c_and_clearance_level_3"
      : kind === "single" ? "clearance_level_2_or_3_and_all_four_gates" : null,
    excludeFromTonnage: false,
    notes: peakSingle
      ? ["Только ветка C прямого 1ПМ при допуске Уровня 3. По умолчанию действует ветка B: сингл не выполняется, цикл идёт на двойках.",
         "Ветка выбирается на контрольной точке №4 (Ц20 B2, T−16), до первой сессии этого цикла.",
         "Пропуск не компенсируется подходами, весом или упражнениями."]
      : [...NOTE[kind]],
  };
  if (kind === "calib" || kind === "test") {
    return { ...base, sets: "1", reps: "3", percent: null, exampleKg: null,
      targetRpe: rng(8, 8), targetRir: null, belowScale: false,
      conditionalLastSet: false, id: `${wid}-${m.key}` };
  }
  const first = rpeOfBar(reps, pct), rl = lastRpe(sets, reps, pct);
  const nn = [...base.notes];
  const ru = (x) => String(x).replace(".", ",");

  if (first === null) {
    // Ниже валидированного диапазона шкалы. Печатать здесь «RPE 1,7» —
    // выдуманная точность: на таких весах шкалу не проверяли.
    nn.push(
      `Вес ${ru(kg(pct))} кг — это ${ru(Math.round(barPct(pct) * 10) / 10)}% RMref, ниже валидированного диапазона шкалы RPE.`,
      "Числовой цели нет: подход заведомо лёгкий. Вес задан планом, а не ощущением — повышать «раз легко» нельзя, для этого есть надбавка Δ.",
    );
    return { ...base, notes: nn, sets: String(sets), reps: String(reps),
      percent: rng(pct), exampleKg: rng(kg(pct)),
      targetRpe: null, targetRir: null, belowScale: true, id: `${wid}-${m.key}` };
  }

  // Никакого зажима: если расчёт выводит за RPE 8, это ошибка спецификации,
  // и её обязан поймать валидатор, а не спрятать генератор.
  if (sets > 1) nn.push(`Целевой RPE: первый подход около ${ru(first)}, последний около ${ru(rl)}.`);
  else nn.push(`Целевой RPE около ${ru(first)}.`);

  // Условный последний подход: при консервативной оценке дрейфа он выходит за 8.
  const pess = lastRpePessimistic(sets, reps, pct);
  const conditionalLastSet = sets > 1 && pess !== null && pess > RPE_CAP;
  if (conditionalLastSet) {
    nn.push(
      `Последний подход условный: выполняется, только если предыдущий пришёл в целевой RPE. При консервативной оценке накопления усталости он выходит на ${ru(pess)}.`,
    );
  }

  return { ...base, notes: nn, sets: String(sets), reps: String(reps),
    percent: rng(pct), exampleKg: rng(kg(pct)),
    targetRpe: rng(Math.min(first, rl), Math.max(first, rl)), targetRir: null,
    belowScale: false, conditionalLastSet, id: `${wid}-${m.key}` };
}
