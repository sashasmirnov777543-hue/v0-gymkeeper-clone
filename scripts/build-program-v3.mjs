// Килограммы на штанге: процент от RMref, к ближайшим 2,5 кг, середина вниз.
const kg = (p) => { const x = (RM * p) / 100, lo = Math.floor(x / 2.5) * 2.5; return x - lo <= lo + 2.5 - x ? lo : lo + 2.5; };
// Фактический процент — от веса, который реально окажется на штанге.
const barPct = (p) => (100 * kg(p)) / RM;

// Нижняя граница валидированной шкалы: RPE 6 в таблице Zourdos/Helms.
// Ниже неё линейная экстраполяция даёт числа, которых шкала не измеряла.
const scaleFloor = (reps) => T[reps][0];

const r1 = (x) => Math.round(x * 10) / 10;
/**
 * RPE первого подхода по ФАКТИЧЕСКОМУ проценту, без округления.
 * Округляется только на выходе: округлять до прибавления дрейфа — значит
 * накапливать ошибку половины шага на каждом подходе. null — ниже шкалы.
 */
const rpeOfBarRaw = (reps, pct) => {
  const row = T[reps], actual = barPct(pct);
  if (actual < row[0]) return null;
  for (let i = 0; i < row.length - 1; i++)
    if (actual >= row[i] && actual <= row[i + 1])
      return RPES[i] + ((actual - row[i]) / (row[i + 1] - row[i])) * (RPES[i + 1] - RPES[i]);
  return 10;
};
const rpeOfBar = (reps, pct) => { const v = rpeOfBarRaw(reps, pct); return v === null ? null : r1(v); };
const lastRpe = (s, r, p) => { const v = rpeOfBarRaw(r, p); return v === null ? null : r1(v + DRIFT * (s - 1)); };
/** Последний подход при консервативной оценке дрейфа — помечает условные подходы. */
const lastRpePessimistic = (s, r, p) => {
  const v = rpeOfBarRaw(r, p);
  return v === null ? null : r1(v + DRIFT_PESSIMISTIC * (s - 1));
};
const rng = (a, b) => ({ min: a, max: b === undefined ? a : b });

